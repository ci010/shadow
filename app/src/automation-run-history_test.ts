import assert from 'node:assert/strict'
import test from 'node:test'
import { createAutomationRunHistory, emptyAutomationRunHistory } from './automation-run-history.ts'
import type { AutomationRunSummary } from './automations.ts'

const settle = () => new Promise(resolve => setTimeout(resolve, 10))
const run = (index: number): AutomationRunSummary => ({
  id: `run-${index}`, sessionId: `web:run-${index}`,
  startedAt: new Date(Date.UTC(2026, 8, 30, 0, -index)).toISOString(), status: 'completed',
})
const rows = Array.from({ length: 65 }, (_, index) => run(index))
function fixture() {
  const state = emptyAutomationRunHistory()
  const requests: Array<{ offset: number; signal: AbortSignal; finish: (rows: AutomationRunSummary[], total?: number, status?: number) => void }> = []
  const request: typeof fetch = async (input, init) => new Promise(resolve => {
    const offset = Number(new URL(String(input)).searchParams.get('offset'))
    requests.push({ offset, signal: init!.signal!, finish: (runs, total = 65, status = 200) =>
      resolve(Response.json({ runs, total, offset }, { status })) })
  })
  const history = createAutomationRunHistory('http://fixture/projects/a', 'job', state, { request, delayMs: 0 })
  return { state, requests, history }
}

test('infinite history loads one page at a time, coalesces requests and retains rows during append', async t => {
  const { state, requests, history } = fixture()
  t.after(history.dispose)
  assert.equal(requests.length, 0)
  history.loadMore()
  assert.equal(requests.length, 0, 'Only an explicit initial refresh starts the resource')
  history.refresh()
  await settle()
  requests[0].finish(rows.slice(0, 30))
  await settle()
  const original = state.runs
  for (let index = 0; index < 20; index++) history.loadMore()
  await settle()
  assert.equal(requests.length, 2)
  assert.equal(requests[1].offset, 30)
  assert.equal(state.runs, original)
  requests[1].finish(rows.slice(30, 60))
  await settle()
  assert.equal(state.runs.length, 60)
  assert.equal(state.nextOffset, 60)
  history.loadMore()
  await settle()
  requests[2].finish(rows.slice(60))
  await settle()
  history.loadMore()
  await settle()
  assert.equal(state.runs.length, 65)
  assert.equal(requests.length, 3, 'Exhausted history does not keep requesting empty pages')
})

test('refresh replays the loaded window atomically, preserving rows on error and handling insertions/deletions', async t => {
  const { state, requests, history } = fixture()
  t.after(history.dispose)
  history.refresh()
  await settle()
  requests[0].finish(rows.slice(0, 30))
  await settle()
  history.loadMore()
  await settle()
  requests[1].finish(rows.slice(30, 60))
  await settle()
  const original = state.runs
  history.refresh()
  await settle()
  const newer = [run(-1), ...rows]
  requests[2].finish(newer.slice(0, 30), 66)
  await settle()
  assert.equal(state.runs, original, 'A partial refreshed window must not replace the existing list')
  requests[3].finish([], 66, 503)
  await settle()
  assert.equal(state.runs, original)
  assert.match(state.error, /Check Main and retry/)
  history.retry()
  await settle()
  requests[4].finish(newer.slice(0, 30), 66)
  await settle()
  requests[5].finish(newer.slice(30, 60), 66)
  await settle()
  assert.equal(state.runs[0].id, 'run--1')
  assert.equal(state.runs.length, 60)
  assert.equal(state.nextOffset, 60)
  assert.equal(state.error, '')
  history.refresh()
  await settle()
  requests[6].finish([run(-1)], 1)
  await settle()
  assert.equal(state.total, 1)
  assert.equal(state.runs.length, 1)
  assert.equal(state.nextOffset, 1)
})

test('append deduplicates shifted pages, retries the same offset and prioritizes queued refreshes', async t => {
  const { state, requests, history } = fixture()
  t.after(history.dispose)
  history.refresh()
  await settle()
  requests[0].finish(rows.slice(0, 30))
  await settle()
  history.loadMore()
  await settle()
  requests[1].finish([], 65, 503)
  await settle()
  assert.equal(state.nextOffset, 30)
  assert.equal(state.runs.length, 30)
  history.retry()
  await settle()
  assert.equal(requests[2].offset, 30)
  for (let index = 0; index < 20; index++) history.refresh()
  requests[2].finish(rows.slice(29, 59), 66)
  await settle()
  assert.equal(state.runs.length, 59, 'Concurrent insertion does not duplicate the boundary run')
  assert.equal(state.nextOffset, 60, 'Wire offset is independent of the deduplicated row count')
  assert.equal(state.loading, true)
  assert.equal(requests[3].offset, 0)
  requests[3].finish(rows.slice(0, 30))
  await settle()
  requests[4].finish(rows.slice(30, 60))
  await settle()
  assert.equal(requests.length, 5)
  assert.equal(state.runs.length, 60)
  assert.equal(state.loading, false)
})

test('disposed history aborts late requests without changing retained data or starting new work', async () => {
  const { state, requests, history } = fixture()
  history.refresh()
  await settle()
  history.dispose()
  assert.equal(requests[0].signal.aborted, true)
  requests[0].finish(rows.slice(0, 30))
  await settle()
  history.refresh()
  history.loadMore()
  history.retry()
  await settle()
  assert.deepEqual(state.runs, [])
  assert.equal(state.loaded, false)
  assert.equal(state.loading, false)
  assert.equal(requests.length, 1)
})
