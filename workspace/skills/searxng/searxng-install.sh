#!/usr/bin/env bash
# SearXNG Docker Installer
# Usage: bash searxng-install.sh [--port=<port>] [--dir=<dir>] [--reinstall]
set -euo pipefail

PORT=8888
BASE_DIR="./searxng"
REINSTALL=false
CONTAINER_NAME="searxng"
IMAGE="docker.io/searxng/searxng:latest"

for arg in "$@"; do
  [[ "$arg" == --port=* ]]    && PORT="${arg#--port=}"
  [[ "$arg" == --dir=* ]]     && BASE_DIR="${arg#--dir=}"
  [[ "$arg" == "--reinstall" ]] && REINSTALL=true
done

log() { echo "[searxng-install] $*"; }
die() { echo "[searxng-install] ERROR: $*" >&2; exit 1; }

# ── Checks ─────────────────────────────────────────────────────────────────────

command -v docker &>/dev/null || die "Docker is not installed. Run the docker-install skill first."

# ── Handle existing container ──────────────────────────────────────────────────

if docker container inspect "$CONTAINER_NAME" &>/dev/null; then
  if $REINSTALL; then
    log "Removing existing container '$CONTAINER_NAME'..."
    docker container stop "$CONTAINER_NAME" 2>/dev/null || true
    docker container rm "$CONTAINER_NAME"
  else
    log "Container '$CONTAINER_NAME' already exists."
    log "Use --reinstall to remove and recreate it."
    log "Current status:"
    docker container inspect "$CONTAINER_NAME" --format '  State: {{.State.Status}}  Ports: {{json .NetworkSettings.Ports}}'
    exit 0
  fi
fi

# ── Pull image ─────────────────────────────────────────────────────────────────

log "Pulling SearXNG image..."
docker pull "$IMAGE"

# ── Create directories ──────────────────────────────────────────────────────────

# realpath -m is not available on macOS; use Python or manual resolution
if command -v realpath &>/dev/null; then
  CONFIG_DIR="$(realpath -m "$BASE_DIR/config")"
  DATA_DIR="$(realpath -m "$BASE_DIR/data")"
elif command -v python3 &>/dev/null; then
  CONFIG_DIR="$(python3 -c "import os,sys; print(os.path.abspath(sys.argv[1]))" "$BASE_DIR/config")"
  DATA_DIR="$(python3 -c "import os,sys; print(os.path.abspath(sys.argv[1]))" "$BASE_DIR/data")"
else
  CONFIG_DIR="$(cd "$(dirname "$BASE_DIR")"; pwd)/$(basename "$BASE_DIR")/config"
  DATA_DIR="$(cd "$(dirname "$BASE_DIR")"; pwd)/$(basename "$BASE_DIR")/data"
fi

log "Creating directories..."
mkdir -p "$CONFIG_DIR" "$DATA_DIR"

# ── Generate settings.yml if missing ──────────────────────────────────────────

SETTINGS_FILE="$CONFIG_DIR/settings.yml"
if [[ ! -f "$SETTINGS_FILE" ]]; then
  SECRET_KEY="$(LC_ALL=C tr -dc 'a-f0-9' < /dev/urandom | head -c 64)"
  log "Generating settings.yml with secret key..."
  cat > "$SETTINGS_FILE" <<EOF
# SearXNG settings — generated by searxng-install.sh
general:
  debug: false
  instance_name: "SearXNG"
  donation_url: false

server:
  secret_key: "${SECRET_KEY}"
  base_url: "http://localhost:${PORT}/"
  bind_address: "0.0.0.0"
  port: 8080

ui:
  static_use_hash: true

search:
  safe_search: 0
  autocomplete: ""
  default_lang: ""
  formats:
    - html
    - json
EOF
  log "Config written to $SETTINGS_FILE"
else
  log "Existing settings.yml found at $SETTINGS_FILE — skipping generation."
fi

# ── Run container ─────────────────────────────────────────────────────────────

log "Starting SearXNG container on port $PORT..."
docker run --name "$CONTAINER_NAME" -d \
  -p "${PORT}:8080" \
  -v "${CONFIG_DIR}:/etc/searxng/" \
  -v "${DATA_DIR}:/var/cache/searxng/" \
  -e "SEARXNG_BASE_URL=http://localhost:${PORT}/" \
  --restart unless-stopped \
  "$IMAGE"

log ""
log "SearXNG is running at: http://localhost:${PORT}"
log "Config directory:      $CONFIG_DIR"
log "Data directory:        $DATA_DIR"
log ""
log "Quick API test:"
log "  curl 'http://localhost:${PORT}/search?q=hello+world&format=json'"
log ""
log "To stop:   docker container stop $CONTAINER_NAME"
log "To start:  docker container start $CONTAINER_NAME"
log "To remove: docker container stop $CONTAINER_NAME && docker container rm $CONTAINER_NAME"
