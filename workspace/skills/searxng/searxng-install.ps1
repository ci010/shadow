#Requires -Version 5.1
<#
.SYNOPSIS
  SearXNG Docker Installer for Windows
.DESCRIPTION
  Pulls the SearXNG Docker image and runs it as a container with config/data volumes.
.PARAMETER Port
  Host port to expose SearXNG on. Default: 8888
.PARAMETER Dir
  Directory to store config and data. Default: .\searxng
.PARAMETER Reinstall
  Stop and remove an existing container before reinstalling.
.EXAMPLE
  .\searxng-install.ps1
  .\searxng-install.ps1 -Port 9090 -Dir C:\searxng
  .\searxng-install.ps1 -Reinstall
#>
param(
  [int]$Port = 8888,
  [string]$Dir = ".\searxng",
  [switch]$Reinstall
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$ContainerName = "searxng"
$Image = "docker.io/searxng/searxng:latest"

function Log { param([string]$Msg) Write-Host "[searxng-install] $Msg" }
function Die { param([string]$Msg) Write-Error "[searxng-install] ERROR: $Msg"; exit 1 }

# ── Check Docker ──────────────────────────────────────────────────────────────

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
  Die "Docker is not installed. Run the docker-install skill first."
}

# ── Handle existing container ─────────────────────────────────────────────────

$exists = docker container inspect $ContainerName 2>&1
if ($LASTEXITCODE -eq 0) {
  if ($Reinstall) {
    Log "Removing existing container '$ContainerName'..."
    docker container stop $ContainerName 2>&1 | Out-Null
    docker container rm $ContainerName | Out-Null
  } else {
    Log "Container '$ContainerName' already exists."
    Log "Use -Reinstall to remove and recreate it."
    docker container inspect $ContainerName --format '  State: {{.State.Status}}'
    exit 0
  }
}

# ── Pull image ────────────────────────────────────────────────────────────────

Log "Pulling SearXNG image..."
docker pull $Image

# ── Create directories ────────────────────────────────────────────────────────

$BaseDir  = [System.IO.Path]::GetFullPath($Dir)
$ConfigDir = Join-Path $BaseDir "config"
$DataDir   = Join-Path $BaseDir "data"

Log "Creating directories..."
New-Item -ItemType Directory -Force -Path $ConfigDir | Out-Null
New-Item -ItemType Directory -Force -Path $DataDir   | Out-Null

# ── Generate settings.yml if missing ─────────────────────────────────────────

$SettingsFile = Join-Path $ConfigDir "settings.yml"
if (-not (Test-Path $SettingsFile)) {
  $SecretKey = -join ((1..64) | ForEach-Object { '{0:x}' -f (Get-Random -Maximum 16) })
  Log "Generating settings.yml with secret key..."
  @"
# SearXNG settings — generated by searxng-install.ps1
general:
  debug: false
  instance_name: "SearXNG"
  donation_url: false

server:
  secret_key: "$SecretKey"
  base_url: "http://localhost:${Port}/"
  bind_address: "0.0.0.0"
  port: 8080

ui:
  static_use_hash: true

search:
  safe_search: 0
  autocomplete: ""
  default_lang: ""
  formats:
    - html
    - json
"@ | Set-Content -Encoding UTF8 $SettingsFile
  Log "Config written to $SettingsFile"
} else {
  Log "Existing settings.yml found — skipping generation."
}

# ── Run container ─────────────────────────────────────────────────────────────

Log "Starting SearXNG container on port $Port..."
docker run --name $ContainerName -d `
  -p "${Port}:8080" `
  -v "${ConfigDir}:/etc/searxng/" `
  -v "${DataDir}:/var/cache/searxng/" `
  -e "SEARXNG_BASE_URL=http://localhost:${Port}/" `
  --restart unless-stopped `
  $Image

Log ""
Log "SearXNG is running at: http://localhost:$Port"
Log "Config directory:      $ConfigDir"
Log "Data directory:        $DataDir"
Log ""
Log "Quick API test:"
Log "  Invoke-WebRequest 'http://localhost:$Port/search?q=hello+world&format=json'"
Log ""
Log "To stop:   docker container stop $ContainerName"
Log "To start:  docker container start $ContainerName"
Log "To remove: docker container stop $ContainerName; docker container rm $ContainerName"
