export const ITEM_ACTIVITY_VIEW = `
CREATE VIEW IF NOT EXISTS initiative_item_activity AS
 SELECT i.*, session_activity(i.assignee_session_id) AS assignee_activity,
 CASE WHEN i.status IN ('pending','in_progress','blocked')
 AND session_activity(i.assignee_session_id)='inactive' THEN 1 ELSE 0 END AS needs_attention,
 CASE WHEN i.status IN ('pending','in_progress','blocked')
 AND session_activity(i.assignee_session_id)='inactive' THEN 1 ELSE 0 END AS needs_handoff
 FROM initiative_items i;
`

export const HANDOFF_VIEW = `
CREATE VIEW IF NOT EXISTS initiative_handoffs AS
 SELECT p.*, session_activity(p.owner_session_id) AS owner_activity,
 1 AS needs_attention, 1 AS needs_handoff FROM initiatives p
 WHERE p.status='active' AND (p.owner_session_id IS NULL OR session_is_inactive(p.owner_session_id)=1);
`

export const SCHEMA = `
CREATE TABLE IF NOT EXISTS initiatives (
 id TEXT PRIMARY KEY, title TEXT NOT NULL, goal TEXT NOT NULL, context TEXT NOT NULL,
 status TEXT NOT NULL CHECK(status IN ('active','completed','cancelled')),
 created_by_session_id TEXT NOT NULL, owner_session_id TEXT,
 created_at TEXT NOT NULL, updated_at TEXT NOT NULL, revision INTEGER NOT NULL CHECK(revision > 0)
) STRICT;
CREATE TABLE IF NOT EXISTS initiative_items (
 id TEXT PRIMARY KEY, initiative_id TEXT NOT NULL REFERENCES initiatives(id),
 title TEXT NOT NULL, status TEXT NOT NULL CHECK(status IN ('pending','in_progress','blocked','done','cancelled')),
 assignee_session_id TEXT, blocked_reason TEXT, updated_at TEXT NOT NULL,
 revision INTEGER NOT NULL CHECK(revision > 0),
 CHECK ((status = 'blocked' AND blocked_reason IS NOT NULL AND length(trim(blocked_reason)) > 0)
     OR (status != 'blocked' AND blocked_reason IS NULL))
) STRICT;
CREATE INDEX IF NOT EXISTS initiative_items_parent ON initiative_items(initiative_id);
CREATE TABLE IF NOT EXISTS initiative_item_deps (
 item_id TEXT NOT NULL REFERENCES initiative_items(id),
 depends_on_item_id TEXT NOT NULL REFERENCES initiative_items(id),
 PRIMARY KEY(item_id, depends_on_item_id), CHECK(item_id != depends_on_item_id)
) STRICT;
CREATE TABLE IF NOT EXISTS initiative_entries (
 id TEXT PRIMARY KEY, initiative_id TEXT NOT NULL REFERENCES initiatives(id),
 item_id TEXT REFERENCES initiative_items(id), author_session_id TEXT NOT NULL,
 kind TEXT NOT NULL, content TEXT NOT NULL, created_at TEXT NOT NULL
) STRICT;
CREATE INDEX IF NOT EXISTS initiative_entries_parent ON initiative_entries(initiative_id, created_at);
CREATE VIEW IF NOT EXISTS initiative_ready_items AS
 SELECT i.* FROM initiative_items i JOIN initiatives p ON p.id=i.initiative_id
 WHERE p.status='active' AND i.status IN ('pending','in_progress') AND NOT EXISTS (
 SELECT 1 FROM initiative_item_deps d JOIN initiative_items dep ON dep.id=d.depends_on_item_id
 WHERE d.item_id=i.id AND dep.status!='done');
CREATE VIEW IF NOT EXISTS initiative_session_todos AS
 SELECT i.* FROM initiative_items i JOIN initiatives p ON p.id=i.initiative_id
 WHERE p.status='active' AND i.assignee_session_id=actor_session_id()
 AND i.status IN ('pending','in_progress','blocked');
${HANDOFF_VIEW}
`
